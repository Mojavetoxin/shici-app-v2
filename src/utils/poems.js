// 取正文首句（首个句读前的短句，去掉换行与空白）
// 例：「点尽苍苔色欲空，竹篱茅舍要诗翁。…」→「点尽苍苔色欲空」
function firstLine(poem) {
  const content = (poem && poem.content) ? String(poem.content) : '';
  const flat = content.replace(/\s+/g, '').replace(/^[\s\u3000]+/, '');
  if (!flat) return '';
  // 中文句读：。！？，；、 以及英文标点
  const m = flat.match(/^[^。！？，；、,.!?;]+/);
  return m ? m[0] : flat;
}

// 显示用标题：统一为「词牌·词题」
//   1) title 已含「·」→ 原样使用
//   2) title 只有词牌或为空 → 用「词牌·正文首句」兜底；首句也取不到时退回词牌
//   3) 词牌也空 → 用已有标题或首句
// 用户自行添加的作品同样走此规则，保证展示一致。
function displayTitle(poem) {
  if (!poem) return '';
  const title = String(poem.title || '').trim();
  const cipai = String(poem.cipai || '').trim();
  if (title.indexOf('·') >= 0) return title;      // 已含词题
  const head = firstLine(poem);
  // 主体名：优先用已有标题（可能是词牌），否则用词牌
  const base = title || cipai;
  if (!base) return head || '';                    // 连词牌都没有，只能给首句
  if (!head || head === base) return base;         // 取不到首句，或首句与主体重名
  return base + '·' + head;
}

// 对一批作品做「显示标题去重」：
// 辛弃疾存在同题多首（如《鹧鸪天·代人赋》两首、《鹧鸪天·鹅湖归病起作》三首），
// 直接展示会同名无法区分。此处给重名者追加首句，得到「词牌·词题（首句）」。
// 返回 { id: 最终标题 } 映射，供各页面统一使用。
function buildDisplayTitles(list) {
  const items = Array.isArray(list) ? list : [];
  const first = {};
  items.forEach(p => {
    const t = displayTitle(p);
    (first[t] = first[t] || []).push(p);
  });
  const map = {};
  Object.keys(first).forEach(t => {
    const group = first[t];
    if (group.length === 1) { map[group[0].id] = t; return; }
    group.forEach(p => {
      const head = firstLine(p);
      map[p.id] = (head && t.indexOf(head) < 0) ? (t + '（' + head + '）') : t;
    });
  });
  return map;
}

// 作者归类：返回 [{ name, count, dynasty }]，按篇数降序（同数按名称稳定排序）。
// 资源库「窗格视图」左栏用它渲染作者列表。
function groupByAuthor(list) {
  const items = Array.isArray(list) ? list : [];
  const map = {};
  items.forEach((p) => {
    const name = String((p && p.author) || '').trim() || '佚名';
    if (!map[name]) map[name] = { name, count: 0, dynasty: '' };
    map[name].count += 1;
    if (!map[name].dynasty) map[name].dynasty = String((p && p.dynasty) || '');
  });
  return Object.keys(map)
    .map((k) => map[k])
    .sort((a, b) => (b.count - a.count) || a.name.localeCompare(b.name, 'zh'));
}

// 体裁归类：返回 [{ name, count }]。诗按「七律/七绝/…」，词统一为「词」。
function groupByType(list) {
  const items = Array.isArray(list) ? list : [];
  const map = {};
  items.forEach((p) => {
    const name = typeOf(p);
    map[name] = (map[name] || 0) + 1;
  });
  return Object.keys(map)
    .map((k) => ({ name: k, count: map[k] }))
    .sort((a, b) => (b.count - a.count) || a.name.localeCompare(b.name, 'zh'));
}

// 词牌归类：只统计有词牌的作品（诗无词牌）。返回 [{ name, count }]。
function groupByCipai(list) {
  const items = Array.isArray(list) ? list : [];
  const map = {};
  items.forEach((p) => {
    const name = String((p && p.cipai) || '').trim();
    if (!name) return;
    map[name] = (map[name] || 0) + 1;
  });
  return Object.keys(map)
    .map((k) => ({ name: k, count: map[k] }))
    .sort((a, b) => (b.count - a.count) || a.name.localeCompare(b.name, 'zh'));
}

// 体裁兜底：老数据可能没有 type 字段，有词牌即视为词，否则用诗体
function typeOf(poem) {
  const t = String((poem && poem.type) || '').trim();
  if (t) return t;
  return String((poem && poem.cipai) || '').trim() ? '词' : '诗';
}

